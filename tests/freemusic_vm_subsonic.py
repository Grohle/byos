#!/usr/bin/env python3
"""freemusic_vm_subsonic.py REPODIR [PORT] : a minimal Subsonic API server for the Vinyl VM test.

Serves the albums generated by tests/freemusic_vm_repo.py (REPODIR) the way Navidrome would:
  /                         a web page (so Vinyl must sniff it as Subsonic through rest/ping)
  /rest/ping.view           auth check (code 10 without parameters, 40 wrong user/password)
  /rest/getScanStatus.view  song count
  /rest/getAlbumList2.view  albums (type newest / alphabeticalByName)
  /rest/search3.view        albums whose name or artist contains "query"
  /rest/getAlbum.view       songs with suffix, size, duration, bitDepth, samplingRate
  /rest/getCoverArt.view    the PNG cover
  /rest/download.view, /rest/stream.view   the files
Auth: user "demo", password "vinyl", token (t = md5(password + s)) or p=enc:<hex>. JSON only.
Only the standard library is used."""
import hashlib, json, os, sys, urllib.parse
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

REPO = sys.argv[1] if len(sys.argv) > 1 else 'vinylrepo'
PORT = int(sys.argv[2]) if len(sys.argv) > 2 else 8773
USER, PASSWORD = 'demo', 'vinyl'
cat = json.load(open(os.path.join(REPO, 'vinyl.json'), encoding='utf-8'))
albums, songs = [], {}
for a in cat['albums']:
    al = {'id': 'al-' + a['id'], 'name': a['title'] + ' (Subsonic)', 'artist': a['artist'], 'year': a['year'], 'coverArt': 'ca-' + a['id'],
          'songCount': len(a['tracks']), 'duration': int(sum(t['duration'] for t in a['tracks'])), 'song': []}
    for n, t in enumerate(a['tracks'], 1):
        f = t['files'][0]
        sid = 'so-%s-%d' % (a['id'], n)
        s = {'id': sid, 'parent': al['id'], 'title': t['title'], 'album': al['name'], 'artist': a['artist'], 'track': n, 'discNumber': 1,
             'size': f['size'], 'suffix': f['codec'], 'contentType': 'audio/' + f['codec'], 'duration': int(t['duration']),
             'bitRate': 1411 if f['codec'] == 'wav' else 2000, 'bitDepth': f.get('bits', 16), 'samplingRate': f.get('rate', 44100), 'channelCount': 2}
        al['song'].append(s); songs[sid] = os.path.join(REPO, f['url'])
    albums.append(al)


def ok(extra):
    r = {'status': 'ok', 'version': '1.16.1', 'type': 'vinyl-test', 'openSubsonic': True}
    r.update(extra)
    return {'subsonic-response': r}


def err(code, msg):
    return {'subsonic-response': {'status': 'failed', 'version': '1.16.1', 'error': {'code': code, 'message': msg}}}


class H(BaseHTTPRequestHandler):
    def send(self, code, body, ctype):
        self.send_response(code); self.send_header('Content-Type', ctype); self.send_header('Content-Length', str(len(body))); self.end_headers()
        self.wfile.write(body)

    def js(self, o):
        self.send(200, json.dumps(o).encode(), 'application/json')

    def do_GET(self):
        u = urllib.parse.urlparse(self.path); q = {k: v[0] for k, v in urllib.parse.parse_qs(u.query).items()}
        if not u.path.startswith('/rest/'):
            return self.send(200, b'<!DOCTYPE html><html><head><title>Navidrome</title></head><body>web UI</body></html>', 'text/html')
        m = u.path[6:].replace('.view', '')
        if 'u' not in q or ('t' not in q and 'p' not in q):
            return self.js(err(10, 'Required parameter is missing'))
        good = q['u'] == USER and (('t' in q and q['t'] == hashlib.md5((PASSWORD + q.get('s', '')).encode()).hexdigest()) or
                                   ('p' in q and q['p'] == 'enc:' + PASSWORD.encode().hex()))
        if not good:
            return self.js(err(40, 'Wrong username or password'))
        lite = lambda a: {k: v for k, v in a.items() if k != 'song'}
        if m == 'ping': return self.js(ok({}))
        if m == 'getScanStatus': return self.js(ok({'scanStatus': {'scanning': False, 'count': len(songs)}}))
        if m == 'getAlbumList2':
            lst = sorted(albums, key=lambda a: a['name']) if q.get('type') == 'alphabeticalByName' else list(reversed(albums))
            off, size = int(q.get('offset', 0)), int(q.get('size', 10))
            return self.js(ok({'albumList2': {'album': [lite(a) for a in lst[off:off + size]]}}))
        if m == 'search3':
            s = q.get('query', '').lower().strip('"')
            return self.js(ok({'searchResult3': {'album': [lite(a) for a in albums if s in a['name'].lower() or s in a['artist'].lower()]}}))
        if m == 'getAlbum':
            for a in albums:
                if a['id'] == q.get('id'): return self.js(ok({'album': a}))
            return self.js(err(70, 'Album not found'))
        if m == 'getCoverArt':
            p = os.path.join(REPO, 'covers', q.get('id', '')[3:] + '.png')
            if os.path.exists(p): return self.send(200, open(p, 'rb').read(), 'image/png')
            return self.js(err(70, 'Cover not found'))
        if m in ('download', 'stream'):
            p = songs.get(q.get('id'))
            if p: return self.send(200, open(p, 'rb').read(), 'audio/flac' if p.endswith('.flac') else 'audio/wav')
            return self.js(err(70, 'Song not found'))
        return self.js(err(0, 'Unknown method ' + m))


print('Subsonic test server on 127.0.0.1:%d (user %s / %s), %d albums' % (PORT, USER, PASSWORD, len(albums)))
ThreadingHTTPServer(('127.0.0.1', PORT), H).serve_forever()
