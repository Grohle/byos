#!/usr/bin/env python3
"""freemusic_vm_flow.py OUT.cmds : writes the Vinyl VM walkthrough for apps/harness_vm/vmdrive.py.

Needs (docs/FREEMUSIC.md, "VM test"): the private VM ~/hiby/vm_vinyl (HIBY_PORT=5572), the local
repository of tests/freemusic_vm_repo.py served on the host at :8771 and the Subsonic stand-in of
tests/freemusic_vm_subsonic.py at :8773 (the guest sees the host as 10.0.2.2). Flow: clean
appdata, open Vinyl, Settings > Sources, add an archive.org collection ("monotonik"), a Vinyl
catalog, an OPML list and a Subsonic server (sniffed from its web page, then user + password),
pull to refresh, reorder, the merged start page, one source at a time, an album of the catalog
(quality badges, download), the search over every source, back and home gestures."""
import sys

KEYS = {}
for row, y, xs in (("qwertyuiop", 274, (22, 53, 84, 115, 145, 176, 207, 238, 269, 299)),
                   ("asdfghjkl", 323, (37, 68, 99, 130, 161, 192, 222, 253, 284)),
                   ("zxcvbnm", 374, (68, 99, 130, 161, 192, 222, 253))):
    for c, x in zip(row, xs):
        KEYS[c] = (0, x, y)
for c, x in zip("1234567890", (22, 53, 84, 115, 145, 176, 207, 238, 269, 299)):
    KEYS[c] = (1, x, 274)
for c, x in zip("-/:", (22, 53, 84)):
    KEYS[c] = (1, x, 323)
KEYS["."] = (1, 68, 374)
KEYS[" "] = (-1, 150, 424)
L = []


def cmd(*a):
    L.append(" ".join(str(x) for x in a))


def typ(text):
    layer = 0
    for ch in text:
        k, x, y = KEYS[ch]
        if k >= 0 and k != layer:
            cmd("tap 35 424"); cmd("sleep 350"); layer = k
        cmd("tap", x, y); cmd("sleep 260")
    if layer:
        cmd("tap 35 424"); cmd("sleep 300")


OK = (280, 424)
SRC_ROW = lambda i: 126 + i * 60 + 30
ADD_ROW = lambda n: 126 + n * 60 + 22
PICK_ROW = lambda i: 126 + i * 44 + 22

cmd("# generated by tests/freemusic_vm_flow.py")
cmd("sh rm -rf /usr/data/hibymod/appdata/freemusic /usr/data/hibymod/cache/freemusic /usr/data/mnt/sd_0/Music/Free")
cmd("restart"); cmd("sleep 4000")
cmd("mark open vinyl"); cmd("tap 53 260"); cmd("sleep 9000"); cmd("shot v20_open_builtin")
cmd("mark settings"); cmd("tap 292 62"); cmd("sleep 1500"); cmd("shot v21_settings")
cmd("mark sources"); cmd("tap 160 168"); cmd("sleep 1500"); cmd("shot v22_sources_builtin")
# 1. archive.org collection, typed as a bare id
cmd("mark add collection"); cmd("tap 80", ADD_ROW(2)); cmd("sleep 1500"); typ("monotonik"); cmd("shot v23_add_collection")
cmd("tap", *OK); cmd("sleep 700"); cmd("shot v24_checking"); cmd("sleep 6000"); cmd("shot v25_collection_ok")
# 2. Vinyl catalog
cmd("mark add catalog"); cmd("tap 80", ADD_ROW(3)); cmd("sleep 1500"); typ("http://10.0.2.2:8771/vinyl.json"); cmd("shot v26_add_catalog")
cmd("tap", *OK); cmd("sleep 4000"); cmd("shot v27_catalog_ok")
# 3. OPML list of feeds
cmd("mark add opml"); cmd("tap 80", ADD_ROW(4)); cmd("sleep 1500"); typ("http://10.0.2.2:8771/feeds.opml")
cmd("tap", *OK); cmd("sleep 4000")
# 4. Subsonic server: only the host, sniffed from the web page; then user and password
cmd("mark add subsonic"); cmd("tap 80", ADD_ROW(5)); cmd("sleep 1500"); typ("http://10.0.2.2:8773")
cmd("tap", *OK); cmd("sleep 5000"); cmd("shot v28_subsonic_user")
typ("demo"); cmd("tap", *OK); cmd("sleep 1500"); typ("vinyl"); cmd("shot v29_subsonic_password"); cmd("tap", *OK); cmd("sleep 5000")
cmd("shot v30_sources_all")
# pull to refresh (held past the arm distance)
cmd("mark pull sources"); cmd("drag 160 150 160 380 700"); cmd("sleep 400"); cmd("shot v31_pull"); cmd("up"); cmd("sleep 4000"); cmd("shot v32_pulled")
# reorder: the catalog (row 3) up
cmd("mark source menu"); cmd("tap 120", SRC_ROW(3)); cmd("sleep 1200"); cmd("shot v33_menu")
cmd("tap 160", 153 + 3 * 46); cmd("sleep 2500"); cmd("shot v34_moved")
# switch off Monotonik (now row 3) and on again
cmd("mark switch"); cmd("tap 266", SRC_ROW(3)); cmd("sleep 1500"); cmd("shot v35_switch_off"); cmd("tap 266", SRC_ROW(3)); cmd("sleep 3000")
# back to the start page: every source merged
cmd("mark back"); cmd("tap 40 52"); cmd("sleep 1200"); cmd("tap 40 52"); cmd("sleep 9000"); cmd("shot v36_root_all")
cmd("drag 160 430 160 130 1500"); cmd("sleep 400"); cmd("up"); cmd("sleep 1500")
for k in range(7):
    cmd("drag 160 430 160 130 1500"); cmd("sleep 400"); cmd("up"); cmd("sleep 2500"); cmd("shot v37_root_all_%d" % k)
# pull to refresh on the start page
cmd("tap 160 100"); cmd("sleep 1500"); cmd("tap 280 424"); cmd("sleep 1500")       # (search bar, empty: back to the top)
# one source at a time: the catalog
cmd("mark pick source"); cmd("tap 65 141"); cmd("sleep 1500"); cmd("shot v38_pick_source")
cmd("tap 160", PICK_ROW(3)); cmd("sleep 4000"); cmd("shot v39_catalog")
cmd("mark pull root"); cmd("drag 160 200 160 430 700"); cmd("sleep 400"); cmd("shot v40_pull_root"); cmd("up"); cmd("sleep 4000")
cmd("mark album"); cmd("tap 160 240"); cmd("sleep 4000"); cmd("shot v41_album")
cmd("drag 160 430 160 200 1200"); cmd("sleep 300"); cmd("up"); cmd("sleep 1500"); cmd("shot v42_album_tracks")
cmd("drag 160 200 160 430 800"); cmd("sleep 300"); cmd("up"); cmd("sleep 1500")
cmd("mark download"); cmd("tap 160 316"); cmd("sleep 1500"); cmd("shot v43_downloading"); cmd("sleep 12000"); cmd("shot v44_downloaded")
cmd("sh ls -R /usr/data/mnt/sd_0/Music/Free | head -20")
cmd("mark back gesture"); cmd("swipe 4 250 250 250 300"); cmd("sleep 2000"); cmd("shot v45_back")
# the OPML feeds, then the Subsonic server
cmd("tap 65 141"); cmd("sleep 1500"); cmd("tap 160", PICK_ROW(5)); cmd("sleep 6000"); cmd("shot v46_opml")
cmd("tap 160 240"); cmd("sleep 4000"); cmd("shot v47_feed_album"); cmd("tap 40 52"); cmd("sleep 1500")
cmd("tap 65 141"); cmd("sleep 1500"); cmd("tap 160", PICK_ROW(6)); cmd("sleep 6000"); cmd("shot v48_subsonic")
cmd("tap 160 240"); cmd("sleep 5000"); cmd("shot v49_subsonic_album"); cmd("tap 40 52"); cmd("sleep 1500")
# search over every source
cmd("tap 65 141"); cmd("sleep 1500"); cmd("tap 160", PICK_ROW(0)); cmd("sleep 3000")
cmd("mark search"); cmd("tap 160 100"); cmd("sleep 1500"); typ("aurora"); cmd("sleep 6000"); cmd("shot v50_search_typing")
cmd("tap", *OK); cmd("sleep 8000"); cmd("shot v51_search_all")
cmd("drag 160 430 160 130 1500"); cmd("sleep 400"); cmd("up"); cmd("sleep 3000"); cmd("shot v52_search_all_2")
cmd("mark home"); cmd("swipe 160 476 160 250 200"); cmd("sleep 2500"); cmd("shot v53_home")
cmd("sh grep -a vinyl /tmp/hibymod/shell.log | tail -40")
cmd("sh cat /usr/data/hibymod/appdata/freemusic/sources.tsv; ls -la /usr/data/hibymod/appdata/freemusic/")
open(sys.argv[1] if len(sys.argv) > 1 else "freemusic_vm.cmds", "w").write("\n".join(L) + "\n")
