    private fun client(p: MockPlayer = player, stall: Int = 45000, finish: Int = 180000) =
        PlayerClient("127.0.0.1", p.port, connectTimeoutMs = 2000, readTimeoutMs = 5000, stallTimeoutMs = stall, finishTimeoutMs = finish)

    private fun expect(kind: TransferException.Kind, block: () -> Unit): TransferException {
        try {
            block()
        } catch (e: TransferException) {
            assertEquals(e.message, kind, e.kind)
            return e
        }
        fail("expected $kind")
        throw AssertionError()
    }

    private fun item(path: String, data: ByteArray) = SendItem(path, data.size.toLong(), sha256Hex(data)) { ByteArrayInputStream(data) }

    /** A stream of [size] generated bytes that are never all in memory. */
    private fun big(size: Long, seed: Int = 7): InputStream = object : InputStream() {
        private val r = TestUtil.Rng(seed)
        private var left = size
        override fun read(): Int = if (left-- > 0) r.next() and 0xff else -1
        override fun read(b: ByteArray, off: Int, len: Int): Int {
            if (left <= 0) return -1
            val n = minOf(len.toLong(), left).toInt()
            for (i in 0 until n) b[off + i] = r.next().toByte()
            left -= n
            return n
        }
    }

    private fun freePort(): Int = ServerSocket(0).use { it.localPort }

    // ------------------------------------------------------------------ addresses

    @Test
    fun readsWhatThePlayerShows() {
        assertEquals("192.168.1.20" to 4399, PlayerClient.parseAddress("http://192.168.1.20:4399"))
        assertEquals("192.168.1.20" to 4399, PlayerClient.parseAddress("  HTTP://192.168.1.20:4399/ "))
        assertEquals("192.168.1.20" to 4399, PlayerClient.parseAddress("192.168.1.20"))
        assertEquals("10.0.0.7" to 8080, PlayerClient.parseAddress("10.0.0.7:8080"))
        assertEquals("player.local" to 4399, PlayerClient.parseAddress("player.local"))
        for (bad in listOf("", " ", "192.168.1", "192.168.1.256", "1.2.3.4.5", "192.168.1.20:", "192.168.1.20:0", "192.168.1.20:70000",
            "192.168.1.20:abc", "http://", "a b", "192.168..20", "-x", "https://192.168.1.20")) {
            assertNull(bad, PlayerClient.parseAddress(bad))
        }
    }

