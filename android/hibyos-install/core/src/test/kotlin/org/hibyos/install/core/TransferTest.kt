    @Test
    fun cardIsFull() {
        player.freeBytes = 100_000
        val a = TestData.gen("random", 1, 60_000)
        val b = TestData.gen("random", 2, 60_000)
        client().upload(home, "a.bin", a.size.toLong(), { ByteArrayInputStream(a) })
        val e = expect(TransferException.Kind.REFUSED) { client().upload(home, "b.bin", b.size.toLong(), { ByteArrayInputStream(b) }) }
        assertEquals(500, e.status)
        assertEquals("""{"error":"Write to file fail"}""", e.serverText)
        // the sender reports it the same way and keeps what was sent
        player.freeBytes = 50_000
        val e2 = expect(TransferException.Kind.REFUSED) { Sender.send(client(), listOf(item("a.bin", a), item("b.bin", b))) }
        assertTrue(e2.message!!, e2.message!!.contains("Write to file fail"))
        assertArrayEquals(a, File(sd, "a.bin").readBytes())
    }

    @Test
    fun playerStopsReceiving() {
        val size = 64L * 1024 * 1024
        player.stallUploadAfter = 200_000
        val t0 = System.nanoTime()
        val e = expect(TransferException.Kind.INTERRUPTED) { client(stall = 700, finish = 700).upload(home, "big.upt", size, { big(size) }) }
        val ms = (System.nanoTime() - t0) / 1_000_000
        assertTrue("gave up after $ms ms: ${e.message}", ms < 15000)
    }

    @Test
    fun playerNeverConfirms() {
        player.neverConfirm = true
        val data = TestData.gen("random", 5, 50_000)
        val t0 = System.nanoTime()
        val e = expect(TransferException.Kind.INTERRUPTED) {
            client(finish = 600).upload(home, "a.bin", data.size.toLong(), { ByteArrayInputStream(data) })
        }
        assertTrue(e.message!!, e.message!!.contains("did not confirm"))
        assertTrue((System.nanoTime() - t0) / 1_000_000 < 10000)
    }

    @Test
    fun cancelStopsAnUploadAtOnce() {
        val size = 64L * 1024 * 1024
        val stop = AtomicBoolean(false)
        val sent = AtomicLong()
        expect(TransferException.Kind.CANCELLED) {
            client().upload(home, "big.upt", size, { big(size) }, { stop.get() }) {
                sent.set(it)
                if (it > 2_000_000) stop.set(true)
            }
        }
        assertTrue(sent.get() < size)
        // also while the player is not taking any more data
        player.stallUploadAfter = 100_000
        val stop2 = AtomicBoolean(false)
        Thread {
            Thread.sleep(600)
            stop2.set(true)
        }.start()
        val t0 = System.nanoTime()
        expect(TransferException.Kind.CANCELLED) { client().upload(home, "big2.upt", size, { big(size) }, { stop2.get() }) }
        assertTrue((System.nanoTime() - t0) / 1_000_000 < 10000)
    }

