    // ------------------------------------------------------------------ the single requests

    @Test
    fun listsCreatesMovesDeletes() {
        val c = client()
        assertTrue(c.list(home).isEmpty())
        assertTrue(c.createDir(home + "HiByOS/"))
        assertFalse("409 means it is already there", c.createDir(home + "HiByOS/"))
        val data = TestData.gen("text", 3, 70000)
        c.upload(home + "HiByOS/", "a file & more (1).txt", data.size.toLong(), { ByteArrayInputStream(data) })
        c.upload(home, "música ñ 音.upt", 3, { ByteArrayInputStream(byteArrayOf(1, 2, 3)) })
        val top = c.list(home).associateBy { it.name }
        assertEquals(setOf("HiByOS", "música ñ 音.upt"), top.keys)
        assertTrue(top["HiByOS"]!!.isDir)
        assertEquals(3L, top["música ñ 音.upt"]!!.size)
        val inside = c.list(home + "HiByOS/")
        assertEquals(1, inside.size)
        assertEquals(data.size.toLong(), inside[0].size)
        assertEquals(home + "HiByOS/a file & more (1).txt", inside[0].path)
        assertArrayEquals(data, File(sd, "HiByOS/a file & more (1).txt").readBytes())
        val md = sha256()
        assertEquals(data.size.toLong(), c.digest(inside[0].path, md))
        assertEquals(sha256Hex(data), Hex.of(md.digest()))
        c.move(inside[0].path, home + "HiByOS/b.txt")
        assertEquals(listOf("b.txt"), c.list(home + "HiByOS/").map { it.name })
        c.delete(home + "HiByOS/b.txt")
        assertTrue(c.list(home + "HiByOS/").isEmpty())
        val e = expect(TransferException.Kind.REFUSED) { c.delete(home + "HiByOS/b.txt") }
        assertEquals(404, e.status)
        expect(TransferException.Kind.REFUSED) { c.list(home + "nothing/") }
        expect(TransferException.Kind.REFUSED) { c.createDir("/etc/x/") }
        expect(TransferException.Kind.LOCAL) { c.upload(home, "a/b", 1, { ByteArrayInputStream(byteArrayOf(1)) }) }
    }

    @Test
    fun uploadsAnEmptyFileAndABigOne() {
        val c = client()
        c.upload(home, "empty", 0, { ByteArrayInputStream(ByteArray(0)) })
        assertEquals(0L, File(sd, "empty").length())
        val size = 9L * 1024 * 1024 + 123
        val seen = AtomicLong()
        c.upload(home, "big.upt", size, { big(size) }) { seen.set(it) }
        assertEquals(size, seen.get())
        val md = sha256()
        val expected = sha256()
        big(size).use { s ->
            val buf = ByteArray(65536)
            while (true) {
                val n = s.read(buf)
                if (n < 0) break
                expected.update(buf, 0, n)
            }
        }
        assertEquals(size, c.digest(home + "big.upt", md))
        assertEquals(Hex.of(expected.digest()), Hex.of(md.digest()))
    }

    // ------------------------------------------------------------------ uploads that go wrong

    @Test
    fun connectionDropsInTheMiddle() {
        val size = 6L * 1024 * 1024
        player.dropUploadAfter = 1_000_000
        val e = expect(TransferException.Kind.INTERRUPTED) { client().upload(home, "big.upt", size, { big(size) }) }
        assertTrue(e.message!!, Regex("the connection broke after \\d+ of $size bytes").containsMatchIn(e.message!!))
        assertFalse(File(sd, "big.upt").exists())
        // trying again works
        client().upload(home, "big.upt", size, { big(size) })
        assertEquals(size, File(sd, "big.upt").length())
    }

    @Test
    fun playerRefusesAtOnce() {
        player.failEarly = true
        for (size in listOf(10L, 8L * 1024 * 1024)) {
            val e = expect(TransferException.Kind.REFUSED) { client().upload(home, "x.upt", size, { big(size) }) }
            assertEquals(500, e.status)
            assertTrue(e.message!!, e.message!!.contains("Read-only file system"))
