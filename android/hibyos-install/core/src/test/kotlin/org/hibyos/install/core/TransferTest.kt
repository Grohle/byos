    @Test
    fun addressesOfTheNetwork() {
        fun ip(a: Int, b: Int, c: Int, d: Int) = byteArrayOf(a.toByte(), b.toByte(), c.toByte(), d.toByte())
        val c24 = Discovery.candidates(ip(192, 168, 1, 37), 24)
        assertEquals(253, c24.size)
        assertEquals("192.168.1.1", c24.first())
        assertEquals("192.168.1.254", c24.last())
        assertFalse(c24.contains("192.168.1.37"))
        // a bigger network: only the neighbours
        val c16 = Discovery.candidates(ip(10, 20, 30, 40), 16)
        assertEquals(253, c16.size)
        assertTrue(c16.all { it.startsWith("10.20.30.") })
        assertEquals(listOf("192.168.200.129", "192.168.200.131", "192.168.200.132", "192.168.200.133", "192.168.200.134"),
            Discovery.candidates(ip(192, 168, 200, 130), 29))
        assertEquals(listOf("172.16.5.2"), Discovery.candidates(ip(172, 16, 5, 1), 30))
        assertEquals(listOf("172.16.5.2"), Discovery.candidates(ip(172, 16, 5, 1), 32))
        assertTrue(Discovery.candidates(ByteArray(16), 64).isEmpty())
    }

    @Test
    fun findsThePlayerAmongOtherAddresses() {
        val hosts = listOf("127.0.0.3", "127.0.0.1", "127.0.0.2")
        var steps = 0
        val seen = ArrayList<String>()
        val found = Discovery.scan(hosts, player.port, connectTimeoutMs = 700, onProgress = { done, total ->
            synchronized(seen) { steps++ }
            assertTrue(done in 1..total)
        }, onFound = { synchronized(seen) { seen += it.host } })
        assertEquals(listOf("127.0.0.1"), found.map { it.host })
        assertEquals("R3II_2025", found[0].name)
        assertTrue(found[0].sdCard)
        assertEquals(listOf("127.0.0.1"), seen)
        assertEquals(3, steps)
        // another device that has the same port open is not a player
        player.impostor = true
        assertTrue(Discovery.scan(hosts, player.port, connectTimeoutMs = 700).isEmpty())
        player.impostor = false
        // nothing there; cancelled before it starts; no addresses
        assertTrue(Discovery.scan(hosts, freePort(), connectTimeoutMs = 500).isEmpty())
        assertTrue(Discovery.scan(hosts, player.port, cancelled = { true }).isEmpty())
        assertTrue(Discovery.scan(emptyList(), player.port).isEmpty())
        // a player without card is still found, and says so
        MockPlayer(null).use { p ->
            val f = Discovery.scan(listOf("127.0.0.1"), p.port, connectTimeoutMs = 700)
            assertEquals(1, f.size)
            assertFalse(f[0].sdCard)
        }
    }
