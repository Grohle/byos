    @Test
    fun worksWhenThePlayerGivesNothingBack() {
        player.noDownload = true
        val items = tree()
        val r = Sender.send(client(), items)
        assertEquals(0, r.verified)
        assertNotNull(r.readBackProblem)
        onCard(items)
        // sizes are still checked
        sd.deleteRecursively(); sd.mkdirs()
        player.storeShort = true
        expect(TransferException.Kind.MISMATCH) { Sender.send(client(), items) }
        // without read-back a file of the right size is sent again rather than trusted
        Sender.send(client(), items)
        val n = player.uploads().size
        Sender.send(client(), items)
        assertEquals(n + items.size, player.uploads().size)
    }

