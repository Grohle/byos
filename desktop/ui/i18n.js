export const LANGS = { en: 'English', fr: 'Français', es: 'Español' };

let lang = 'en';

export function setLang(l) {
  lang = Object.hasOwn(STRINGS, l) ? l : 'en';
  return lang;
}

export function getLang() {
  return lang;
}

export function detectLang(list) {
  for (const l of list || []) {
    const base = String(l).toLowerCase().split('-')[0];
    if (Object.hasOwn(STRINGS, base)) return base;
  }
  return 'en';
}

// Plural forms: with a numeric { count }, t() uses "KEY_one" (or another CLDR category, if
// present) when the language says so for that count, and KEY otherwise.
const plurals = new Map();
function pluralForm(key, count) {
  let pr = plurals.get(lang);
  if (!pr) { pr = new Intl.PluralRules(lang); plurals.set(lang, pr); }
  const form = `${key}_${pr.select(count)}`;
  if (Object.hasOwn(STRINGS[lang], form)) return STRINGS[lang][form];
  // English's form only when this language has no text of its own for the key
  if (!Object.hasOwn(STRINGS[lang], key) && Object.hasOwn(STRINGS.en, form)) return STRINGS.en[form];
  return null;
}

export function t(key, vars) {
  let s = (vars && typeof vars.count === 'number' && pluralForm(key, vars.count)) || (STRINGS[lang][key] ?? STRINGS.en[key] ?? key);
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

// The message for a byos-cli "error" line: by BTP name first, then by CLI code, then the
// CLI's own English message.
export function errorMessage(err) {
  if (!err) return t('err_internal');
  if (err.code === 'timeout' && err.reason === 'prompt') return t('err_prompt_timeout');
  const btp = err.btp && err.btp.name;
  if (btp && (STRINGS[lang]['err_' + btp] || STRINGS.en['err_' + btp])) return t('err_' + btp);
  if (STRINGS[lang]['err_' + err.code] || STRINGS.en['err_' + err.code]) return t('err_' + err.code);
  return err.message || t('err_internal');
}
